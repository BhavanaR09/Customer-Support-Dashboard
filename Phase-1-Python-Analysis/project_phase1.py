"""2. Data Cleaning Using Python"""

#A. Clean dates and drop missing rows
# Explicitly parse dates first to avoid warnings and handle formatting
df['CreatedDate'] = pd.to_datetime(df['CreatedDate'], dayfirst=True)
df['ResolvedDate'] = pd.to_datetime(df['ResolvedDate'], dayfirst=True)

# Drop rows with null values if that is your intended cleaning strategy
# Note: This will significantly reduce rows (down to ~3,979) due to open/pending tickets lacking resolution dates.
df_cleaned = df.dropna()
display(df_cleaned.head())

#B. Fill missing values
# Replacing 'column_name' with actual columns containing missing values, like 'Region'
df["Region"] = df["Region"].fillna("Unknown")
df["CustomerID"] = df["CustomerID"].fillna("Unknown")
df["ResolvedDate"] = df["ResolvedDate"].fillna("Unknown")
df["ResolutionTimeHours"] = df["ResolutionTimeHours"].fillna("Unknown")
df["SatisfactionScore"] = df["SatisfactionScore"].fillna("Unknown")



# Let's check the updated missing value counts
df.isnull().sum()

#C. Remove duplicates
# Remove duplicate rows and save the changes to the DataFrame
df = df.drop_duplicates()
print(f"DataFrame shape after removing duplicates: {df.shape}")

#D. Correct data types
# Explicitly pass dayfirst=True to correctly parse day-first formats (e.g. DD-MM-YYYY)
df["CreatedDate"] = pd.to_datetime(df["CreatedDate"], dayfirst=True)
print("CreatedDate datatype:", df["CreatedDate"].dtype)

#Checking the data types of each column in the DataFrame
df.dtypes

# Converting ResolvedDate to datetime (handling 'Unknown' as NaT)
df['ResolvedDate'] = pd.to_datetime(df['ResolvedDate'], dayfirst=True, errors='coerce')

# Converting ResolutionTimeHours and SatisfactionScore to numeric (handling 'Unknown' as NaN)
df['ResolutionTimeHours'] = pd.to_numeric(df['ResolutionTimeHours'], errors='coerce')
df['SatisfactionScore'] = pd.to_numeric(df['SatisfactionScore'], errors='coerce')

# Displaying the updated data types to verify changes
display(df.dtypes)

